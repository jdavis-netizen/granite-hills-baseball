// Builds the baseball cards on roster.html from the roster table and the stats tables.
// Run after a roster or stats change:  node tools/build-cards.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');
const clean = s => s.replace(/<[^>]*>/g, '').replace(/&mdash;/g, '').replace(/&amp;/g, '&').trim();
const cellsOf = row => (row.match(/<td[^>]*>[\s\S]*?<\/td>/g) || []).map(clean);
const esc = s => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;');

const rosterHtml = read('roster.html');
const rosterTable = rosterHtml.slice(rosterHtml.indexOf('id="roster-varsity"'));
const players = (rosterTable.slice(rosterTable.indexOf('<tbody>'), rosterTable.indexOf('</tbody>')).match(/<tr>[\s\S]*?<\/tr>/g) || [])
  .map(cellsOf).map(([num, name, pos, gr, ht, wt]) => ({ num, name, pos, gr, ht, wt }));

const statsHtml = read('stats.html');
const tables = statsHtml.match(/<table class="stats-tbl">[\s\S]*?<\/table>/g) || [];
function statTable(html) {
  const heads = (html.match(/<th[^>]*>[\s\S]*?<\/th>/g) || []).map(clean);
  const out = {};
  for (const row of html.match(/<tr[^>]*>\s*<td[\s\S]*?<\/tr>/g) || []) {
    const c = cellsOf(row);
    if (c[1]) out[c[1]] = Object.fromEntries(heads.map((h, i) => [h, c[i]]));
  }
  return out;
}
const batting = statTable(tables[0]);
const pitching = statTable(tables[1]);

const GRADE = { 'Fr.': 'Freshman', 'So.': 'Sophomore', 'Jr.': 'Junior', 'Sr.': 'Senior' };
const line = (label, value) => `<div class="pc-stat"><dt>${label}</dt><dd>${value}</dd></div>`;

function card(p) {
  const b = batting[p.name];
  const k = pitching[p.name];
  const bat = b ? `<h4 class="pc-head">2026 Hitting</h4><dl class="pc-stats">${['AVG', 'H', 'HR', 'RBI', 'R', 'OPS'].map(s => line(s, b[s])).join('')}</dl>` : '';
  const pit = k ? `<h4 class="pc-head">2026 Pitching</h4><dl class="pc-stats">${['ERA', 'W', 'SV', 'IP', 'K', 'BB'].map(s => line(s, k[s])).join('')}</dl>` : '';
  const none = !b && !k ? '<p class="pc-none">No 2026 varsity stats</p>' : '';
  const label = `Flip ${p.name}'s card to see 2026 stats`;
  return `        <li class="pc-wrap">
          <div class="pc">
            <button class="pc-flip" type="button" aria-pressed="false" aria-label="${esc(label)}"></button>
            <div class="pc-inner">
              <div class="pc-face pc-front">
                <span class="pc-foil" aria-hidden="true"></span>
                <img class="pc-eagle" src="images/Eagle head   new 2023.png" alt="" width="90" height="90" loading="lazy">
                <span class="pc-num">${p.num || 'GH'}</span>
                <span class="pc-name">${p.name}</span>
                <span class="pc-sub">${p.pos} <i aria-hidden="true"></i> ${GRADE[p.gr] || p.gr}</span>
                <span class="pc-size">${p.ht} &middot; ${p.wt} lb</span>
              </div>
              <div class="pc-face pc-back">
                <span class="pc-back-name">${p.name}</span>
                ${bat}${pit}${none}
                <span class="pc-back-foot">Granite Hills Baseball 2026</span>
              </div>
            </div>
          </div>
        </li>`;
}

const block = `<!-- CARDS:START (generated by tools/build-cards.js) -->
      <ul class="pc-grid" id="playerCards">
${players.map(card).join('\n')}
      </ul>
      <!-- CARDS:END -->`;

let out = rosterHtml;
if (out.includes('<!-- CARDS:START')) {
  out = out.replace(/<!-- CARDS:START[\s\S]*?<!-- CARDS:END -->/, () => block);
} else {
  throw new Error('Add the CARDS markers to roster.html first');
}
fs.writeFileSync(path.join(root, 'roster.html'), out);
console.log(players.length, 'cards;', players.filter(p => batting[p.name]).length, 'with hitting;', players.filter(p => pitching[p.name]).length, 'with pitching');
console.log('In stats but not roster:', [...Object.keys(batting), ...Object.keys(pitching)].filter(n => !players.some(p => p.name === n) && !/total/i.test(n)));
