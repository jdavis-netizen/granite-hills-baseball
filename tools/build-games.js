// Builds js/games.js and the subscribable calendar files from schedule.html.
// Run after any schedule change:  node tools/build-games.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'schedule.html'), 'utf8');
const strip = s => s.replace(/<[^>]*>/g, ' ').replace(/&bull;/g, '•').replace(/&ndash;/g, '-').replace(/&amp;/g, '&').replace(/&[a-z]+;/g, ' ').replace(/\s+/g, ' ').trim();
const MONTHS = { Jan: 1, Feb: 2, Mar: 3, Apr: 4, May: 5, Jun: 6 };
const YEAR = 2027;

function toIso(dateText, timeText) {
  const m = dateText.match(/([A-Z][a-z]{2})\w*\s+(\d{1,2})/);
  if (!m || !MONTHS[m[1]]) return null;
  const d = `${YEAR}-${String(MONTHS[m[1]]).padStart(2, '0')}-${m[2].padStart(2, '0')}`;
  const t = (timeText || '').match(/(\d{1,2})(?::(\d{2}))?\s*(AM|PM)/i);
  const range = dateText.match(/-\s*(\d{1,2})\s*$/); // "Mar 22-25": a multi-day event
  if (range) return { date: d, time: null, end: `${YEAR}-${String(MONTHS[m[1]]).padStart(2, '0')}-${range[1].padStart(2, '0')}` };
  if (!t) return { date: d, time: null };
  let h = +t[1] % 12; if (/pm/i.test(t[3])) h += 12;
  return { date: d, time: `${String(h).padStart(2, '0')}:${t[2] || '00'}` };
}

const games = [];
// Winter ball list
const wb = html.slice(html.indexOf('wb-list'), html.indexOf('sched-card-foot'));
for (const li of wb.match(/<li>[\s\S]*?<\/li>/g) || []) {
  const date = strip((li.match(/class="sd">([\s\S]*?)<\/span>/) || [])[1] || '');
  const opp = strip((li.match(/class="so">([\s\S]*?)<\/span>/) || [])[1] || '');
  const site = strip((li.match(/class="wb-site">([\s\S]*?)<\/span>/) || [])[1] || '');
  const time = strip((li.match(/class="st">([\s\S]*?)<\/span>/) || [])[1] || '');
  const when = toIso(date, time);
  if (when) games.push({ team: 'Winter', ...when, label: date, opp: opp.replace(/^(vs|@)\s+/, ''), away: /^@/.test(opp), site, event: 'Winter Ball', timeText: time });
}
// Spring tables, by level
for (const [id, team] of [['varsity', 'Varsity'], ['jv', 'JV'], ['freshman', 'Freshman']]) {
  const start = html.indexOf(`id="${id}"`);
  if (start < 0) continue;
  const next = html.slice(start + 5).search(/id="\w+" class="schedule-level/);
  const block = next < 0 ? html.slice(start) : html.slice(start, start + 5 + next);
  for (const table of block.match(/<table class="schedule-table">[\s\S]*?<\/table>/g) || []) {
    const heads = (table.match(/<th[^>]*>[\s\S]*?<\/th>/g) || []).map(strip).map(s => s.toLowerCase());
    for (const row of table.split('<tbody>')[1].match(/<tr[\s\S]*?<\/tr>/g) || []) {
      const cells = (row.match(/<td[^>]*>[\s\S]*?<\/td>/g) || []).map(strip);
      const get = k => { const i = heads.indexOf(k); return i < 0 ? '' : (cells[i] || ''); };
      const when = toIso(get('date'), get('time'));
      if (!when) continue;
      const opp = get('opponent');
      const loc = get('location');
      games.push({ team, ...when, label: get('date'), opp: opp.replace(/^(vs\.?|@|at)\s+/i, ''), away: /away/i.test(loc), site: loc, event: get('event') || get('league') || 'Spring', timeText: get('time') });
    }
  }
}
games.sort((a, b) => (a.date + (a.time || '')).localeCompare(b.date + (b.time || '')));
fs.writeFileSync(path.join(root, 'js/games.js'), '// Generated by tools/build-games.js from schedule.html. Do not edit by hand.\nwindow.GH_GAMES = ' + JSON.stringify(games, null, 0).replace(/\},\{/g, '},\n{') + ';\n');

// .ics files: one for varsity + winter, one per other level
const esc = s => String(s).replace(/([,;\\])/g, '\\$1');
function ics(list, name) {
  const lines = ['BEGIN:VCALENDAR', 'VERSION:2.0', 'PRODID:-//Granite Hills Baseball//Schedule//EN', 'CALSCALE:GREGORIAN', `X-WR-CALNAME:${esc(name)}`, 'X-WR-TIMEZONE:America/Los_Angeles'];
  for (const g of list) {
    const day = g.date.replace(/-/g, '');
    const uid = `${g.team}-${day}-${g.opp}`.replace(/[^A-Za-z0-9-]/g, '') + '@granitehillsbaseball';
    lines.push('BEGIN:VEVENT', `UID:${uid}`, `DTSTAMP:${YEAR - 1}1101T000000Z`);
    if (g.time) {
      const [h, m] = g.time.split(':').map(Number);
      const endH = String(h + 2).padStart(2, '0');
      lines.push(`DTSTART;TZID=America/Los_Angeles:${day}T${g.time.replace(':', '')}00`, `DTEND;TZID=America/Los_Angeles:${day}T${endH}${String(m).padStart(2, '0')}00`);
    } else {
      lines.push(`DTSTART;VALUE=DATE:${day}`);
      if (g.end) {
        const after = new Date(g.end + 'T12:00:00Z');
        after.setUTCDate(after.getUTCDate() + 1);
        lines.push(`DTEND;VALUE=DATE:${after.toISOString().slice(0, 10).replace(/-/g, '')}`);
      }
    }
    lines.push(`SUMMARY:${esc(`GH ${g.team === 'Winter' ? 'Winter Ball' : g.team} ${g.away ? '@' : 'vs'} ${g.opp}`)}`);
    lines.push(`DESCRIPTION:${esc([g.event, g.site, g.time ? '' : 'Time to be announced'].filter(Boolean).join(' - '))}`, 'END:VEVENT');
  }
  lines.push('END:VCALENDAR');
  return lines.join('\r\n') + '\r\n';
}
fs.mkdirSync(path.join(root, 'cal'), { recursive: true });
fs.writeFileSync(path.join(root, 'cal/varsity.ics'), ics(games.filter(g => g.team === 'Varsity' || g.team === 'Winter'), 'Granite Hills Baseball'));
fs.writeFileSync(path.join(root, 'cal/jv.ics'), ics(games.filter(g => g.team === 'JV'), 'Granite Hills JV Baseball'));
