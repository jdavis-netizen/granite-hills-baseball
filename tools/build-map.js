// Builds the "Where the Eagles Play" map on tracker.html from the tracker cards.
// Needs us-atlas, d3-geo, topojson-client and topojson-simplify on NODE_PATH or locally.
// Add a new school to PLACES when a tracker card names one.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const d3 = require('d3-geo');
const topo = require('topojson-client');
const simplify = require('topojson-simplify');
const fullAtlas = require('us-atlas/states-10m.json');
const pre = simplify.presimplify(fullAtlas);
const atlas = simplify.simplify(pre, simplify.quantile(pre, 0.12));

// Team name on the tracker card -> map spot. Schools within a few miles at this scale share a spot.
const SPOTS = {
  sd: { name: 'San Diego County', at: [-117.05, 32.85] },
  phx: { name: 'Phoenix Area, AZ', at: [-111.98, 33.47] },
  ie: { name: 'Inland Empire, CA', at: [-117.55, 34.0] },
  sb: { name: 'Santa Barbara, CA', at: [-119.85, 34.41] },
  bay: { name: 'Santa Clara, CA', at: [-121.94, 37.35] },
  stk: { name: 'Stockton, CA', at: [-121.31, 37.98] },
  pul: { name: 'Pullman, WA', at: [-117.16, 46.73] },
  van: { name: 'Vancouver, BC', at: [-123.1, 49.24] },
  pue: { name: 'Pueblo, CO', at: [-104.58, 38.31] },
  kan: { name: 'Baldwin City, KS', at: [-95.19, 38.78] },
  tex: { name: 'Sugar Land, TX', at: [-95.63, 29.62] },
  nia: { name: 'Niagara, NY', at: [-79.04, 43.14] },
};
const PLACES = [
  ['Sugar Land', 'tex'], ['Vancouver', 'van'], ['Arizona State', 'phx'], ['Washington State', 'pul'], ['Santa Clara', 'bay'],
  ['Pacific', 'stk'], ['Cal Baptist', 'ie'], ['Santa Barbara', 'sb'], ['Niagara', 'nia'], ['CSU-Pueblo', 'pue'],
  ['Arizona Christian', 'phx'], ['La Verne', 'ie'], ['Cal State San Marcos', 'sd'], ['Baker', 'kan'], ['Grossmont', 'sd'], ['Southwestern', 'sd'],
];

let html = fs.readFileSync(path.join(root, 'tracker.html'), 'utf8');
const LEVEL = { pro: 'Pro', milb: 'Pro', d1: 'D1', d2: 'D2', d3: 'D3', naia: 'NAIA', juco: 'JUCO' };
const players = [];
const re = /tracker-level-(\w+)[\s\S]*?<h3>(.*?)<\/h3>\s*<div class="tracker-team">(.*?)<\/div>/g;
let m;
while ((m = re.exec(html))) {
  const place = PLACES.find(([k]) => m[3].includes(k));
  if (!place) throw new Error('No map spot for team: ' + m[3]);
  players.push({ level: LEVEL[m[1]] || m[1], name: m[2], team: m[3], spot: place[1] });
}

const W = 960, H = 600;
const states = topo.feature(atlas, atlas.objects.states);
states.features = states.features.filter(f => !['02', '15', '60', '66', '69', '72', '78'].includes(String(f.id)));
const projection = d3.geoConicConformal().parallels([29.5, 45.5]).rotate([98, 0]).fitExtent([[18, 34], [W - 18, H - 14]], states);
const geo = d3.geoPath(projection);
const round = d => d.replace(/(\d+)\.\d+/g, '$1');
const land = states.features.map(f => `<path d="${round(geo(f))}"/>`).join('');
const home = projection([-116.93, 32.8]);

const spots = Object.entries(SPOTS).map(([id, s]) => ({ id, ...s, list: players.filter(p => p.spot === id) })).filter(s => s.list.length);
function arc(a, b) {
  const [x0, y0] = a, [x1, y1] = b;
  const d = Math.hypot(x1 - x0, y1 - y0);
  const cx = (x0 + x1) / 2, cy = (y0 + y1) / 2 - Math.max(16, d * 0.22);
  return `M${x0.toFixed(1)} ${y0.toFixed(1)}Q${cx.toFixed(1)} ${cy.toFixed(1)} ${x1.toFixed(1)} ${y1.toFixed(1)}`;
}
const marks = spots.map(s => {
  const p = projection(s.at);
  const near = s.id === 'sd';
  const r = 5 + Math.sqrt(s.list.length) * 2.6;
  const count = s.list.length > 1 ? `<text class="em-count" x="${p[0].toFixed(1)}" y="${(p[1] + 4.5).toFixed(1)}">${s.list.length}</text>` : '';
  const hit = `<circle class="em-hit" cx="${p[0].toFixed(1)}" cy="${p[1].toFixed(1)}" r="22"/>`;
  return `<g class="em-spot" data-spot="${s.id}" tabindex="0" role="button" aria-label="${s.name}: ${s.list.map(x => x.name).join(', ')}">${near ? '' : `<path class="em-arc" pathLength="1" d="${arc(home, p)}"/>`}${hit}<circle class="em-dot" cx="${p[0].toFixed(1)}" cy="${p[1].toFixed(1)}" r="${r.toFixed(1)}"/>${count}</g>`;
}).join('\n          ');

const places = spots.slice().sort((a, b) => b.list.length - a.list.length).map(s => `<li class="em-place" data-spot="${s.id}"><button type="button"><span class="em-place-name">${s.name}</span><span class="em-place-count">${s.list.length}</span></button><ul>${s.list.map(p => `<li><strong>${p.name}</strong> ${p.team} <em>${p.level}</em></li>`).join('')}</ul></li>`).join('\n          ');

const block = `<!-- MAP:START (generated by tools/build-map.js) -->
  <section class="section section-dark eagle-map" id="map">
    <div class="container">
      <div class="section-header">
        <h2>Where the Eagles Play</h2>
        <div class="accent-line"></div>
      </div>
      <p class="em-lede">${players.length} Eagles on this page, in ${spots.length} places. Every line starts at Granite Hills. Tap a spot to see who is there.</p>
      <div class="em-layout">
        <svg class="em-svg" viewBox="0 0 ${W} ${H}" role="img" aria-label="Map of North America with a line from El Cajon to each place Granite Hills alumni are playing. The list beside it has the same information.">
          <g class="em-land">${land}</g>
          ${marks}
          <g class="em-home"><circle cx="${home[0].toFixed(1)}" cy="${home[1].toFixed(1)}" r="3.5"/></g>
        </svg>
        <ul class="em-list">
          ${places}
        </ul>
      </div>
    </div>
  </section>
  <!-- MAP:END -->`;

if (!html.includes('<!-- MAP:START')) throw new Error('Add the MAP markers to tracker.html first');
html = html.replace(/<!-- MAP:START[\s\S]*?<!-- MAP:END -->/, () => block);
fs.writeFileSync(path.join(root, 'tracker.html'), html);
console.log(players.length, 'players in', spots.length, 'spots;', (block.length / 1024).toFixed(0) + ' KB');
